"""Build the optional local Official WebEngine component."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import zipfile


ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
sys.path.insert(0, str(SRC))

from ai_quiz_overlay.branding import APP_VERSION
from ai_quiz_overlay.services.official_web import (
    OFFICIAL_LOGIN_COMPONENT_VERSION,
)
from ai_quiz_overlay.services.official_web_component import (
    COMPONENT_MANIFEST_NAME,
    manifest_bytes_for_files,
)


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _write_expected_module(path: Path, manifest_hash: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        '"""Generated by build/build_official_web_component.py."""\n\n'
        "EXPECTED_OFFICIAL_WEB_MANIFEST_SHA256 = "
        f'"{manifest_hash}"\n',
        encoding="utf-8",
        newline="\n",
    )


def _build_component_tree(
    output_dir: Path,
    component_version: str,
    app_version: str,
) -> Path:
    work_dir = output_dir / ".build"
    spec_dir = work_dir / "spec"
    dist_dir = work_dir / "dist"
    build_dir = work_dir / "pyinstaller"
    if work_dir.exists():
        shutil.rmtree(work_dir)
    spec_dir.mkdir(parents=True)
    command = [
        sys.executable,
        "-m",
        "PyInstaller",
        "--onedir",
        "--windowed",
        "--noconfirm",
        "--clean",
        "--name",
        "official-web-host",
        "--distpath",
        str(dist_dir),
        "--workpath",
        str(build_dir),
        "--specpath",
        str(spec_dir),
        "--paths",
        str(SRC),
        "--paths",
        str(ROOT / "component"),
        "--hidden-import",
        "official_web_browser_host",
    ]
    command.append(str(ROOT / "component" / "official_web_host.py"))
    subprocess.run(command, cwd=ROOT, check=True)
    built_root = dist_dir / "official-web-host"
    if not (built_root / "official-web-host.exe").is_file():
        raise RuntimeError("PyInstaller did not produce official-web-host.exe")
    manifest = manifest_bytes_for_files(
        built_root,
        component_version=component_version,
        app_version=app_version,
        entrypoint="official-web-host.exe",
    )
    (built_root / COMPONENT_MANIFEST_NAME).write_bytes(manifest)
    return built_root


def _write_zip(source_root: Path, output: Path) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(
        output,
        "w",
        compression=zipfile.ZIP_DEFLATED,
        compresslevel=6,
    ) as archive:
        manifest = source_root / COMPONENT_MANIFEST_NAME
        archive.write(manifest, COMPONENT_MANIFEST_NAME)
        for path in sorted(source_root.rglob("*")):
            if not path.is_file() or path == manifest:
                continue
            relative = path.relative_to(source_root).as_posix()
            archive.write(path, relative)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=ROOT / "outputs" / "official-web-component",
    )
    parser.add_argument(
        "--expected-module",
        type=Path,
        default=(
            SRC
            / "ai_quiz_overlay"
            / "services"
            / "official_web_component_expected.py"
        ),
    )
    parser.add_argument(
        "--component-version",
        default=OFFICIAL_LOGIN_COMPONENT_VERSION,
    )
    parser.add_argument("--app-version", default=APP_VERSION)
    parser.add_argument(
        "--from-folder",
        type=Path,
        help="Package an existing built component folder without PyInstaller.",
    )
    args = parser.parse_args()
    output_dir = args.output_dir.resolve()
    if args.from_folder is not None:
        source_root = args.from_folder.resolve()
        manifest = manifest_bytes_for_files(
            source_root,
            component_version=args.component_version,
            app_version=args.app_version,
            entrypoint="official-web-host.exe",
        )
        (source_root / COMPONENT_MANIFEST_NAME).write_bytes(manifest)
    else:
        source_root = _build_component_tree(
            output_dir,
            args.component_version,
            args.app_version,
        )
    manifest_hash = hashlib.sha256(
        (source_root / COMPONENT_MANIFEST_NAME).read_bytes()
    ).hexdigest()
    archive_path = output_dir / "official-web-component.zip"
    _write_zip(source_root, archive_path)
    _write_expected_module(args.expected_module.resolve(), manifest_hash)
    result = {
        "component_version": args.component_version,
        "app_version": args.app_version,
        "manifest_sha256": manifest_hash,
        "zip": str(archive_path),
        "expected_module": str(args.expected_module.resolve()),
    }
    print(json.dumps(result, ensure_ascii=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
